const fs = require("node:fs");
const path = require("node:path");
const postcss = require("postcss");

const sourcePath = path.join(__dirname, "../src/features/landing/landing-source.ts");
const outputPath = path.join(__dirname, "../src/features/landing/landing-scoped-css.ts");
const source = fs.readFileSync(sourcePath, "utf8");
const startMarker = "export const landingCss = String.raw`";
const start = source.indexOf(startMarker);
if (start < 0) throw new Error("landingCss was not found");
const cssStart = start + startMarker.length;
const cssEnd = source.indexOf("`;", cssStart);
if (cssEnd < 0) throw new Error("landingCss closing marker was not found");

const root = postcss.parse(source.slice(cssStart, cssEnd));
root.walkRules((rule) => {
  for (let parent = rule.parent; parent; parent = parent.parent) {
    if (parent.type === "atrule" && /keyframes$/i.test(parent.name)) return;
  }

  rule.selector = postcss.list.comma(rule.selector).map((selector) => {
    const trimmed = selector.trim();
    if (/^:root\[data-theme\s*=/.test(trimmed)) {
      return trimmed.replace(/^(:root\[data-theme\s*=\s*(?:"[^"]+"|'[^']+'|[^\]]+)\])/, "$1 .landing-page");
    }
    if (trimmed === ":root" || trimmed === "html" || trimmed === "body") {
      return ".landing-page";
    }
    return `.landing-page ${trimmed}`;
  }).join(", ");
});

const output = `// Generated by scripts/scope-landing-css.cjs. Edit landing-source.ts instead.\nexport const scopedLandingCss = String.raw\`${root.toString()}\`;\n`;
fs.writeFileSync(outputPath, output);
